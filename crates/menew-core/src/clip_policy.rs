//! What the clipboard capture does with a copy, decided without touching the clipboard: which of the
//! offered types to read (`ClipboardManager.poll` reads files, then text, then images), whether it
//! is marked as a password, whether capture is paused or the app is ignored, and the names and sizes
//! of images. Pure and tested; `docs/clipboard-spec.md` has the vectors.

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

/// The biggest thing taken from the clipboard. The Mac has no limit; 20 MB keeps a copied photo
/// from filling the history and a D-Bus message.
pub const MAX_BYTES: usize = 20 * 1024 * 1024;

/// Types that password managers use to say "do not keep this": the ones of the Mac
/// (`ClipboardManager.ignoredTypes`) plus the one of KeePassXC and the KDE clipboard.
pub fn is_secret_type(mime: &str) -> bool {
    let m = mime.to_lowercase();
    m.contains("password") || m.contains("secret") || m.contains("concealedtype") || m.contains("transienttype") || m.contains("autogeneratedtype") || m.contains("onepassword")
}

pub fn has_secret_type(types: &[String]) -> bool {
    types.iter().any(|t| is_secret_type(t))
}

/// Something that can be read from the clipboard, with the type to ask for.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Candidate {
    /// `text/uri-list` with `file://` addresses.
    Files(String),
    Text(String),
    Image(String),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Skip {
    /// Marked as a password, a one-time value or generated by a password manager.
    Secret,
}

const TEXT_TYPES: [&str; 5] = ["text/plain;charset=utf-8", "text/plain", "utf8_string", "string", "text"];
const IMAGE_TYPES: [&str; 8] = ["image/png", "image/jpeg", "image/jpg", "image/webp", "image/gif", "image/bmp", "image/x-bmp", "image/tiff"];

fn pick<'a>(types: &'a [String], wanted: &[&str]) -> Option<&'a String> {
    wanted.iter().find_map(|w| types.iter().find(|t| t.eq_ignore_ascii_case(w)))
}

/// In what order to try the types a copy offers. `Err` when it must not be read at all.
pub fn plan(types: &[String]) -> Result<Vec<Candidate>, Skip> {
    if has_secret_type(types) {
        return Err(Skip::Secret);
    }
    let mut out = vec![];
    if let Some(t) = types.iter().find(|t| t.eq_ignore_ascii_case("text/uri-list")) {
        out.push(Candidate::Files(t.clone()));
    }
    if let Some(t) = pick(types, &TEXT_TYPES) {
        out.push(Candidate::Text(t.clone()));
    }
    if let Some(t) = pick(types, &IMAGE_TYPES) {
        out.push(Candidate::Image(t.clone()));
    }
    Ok(out)
}

/// The paths of the `file://` lines of a `text/uri-list` (other addresses and `#` comments are left out).
pub fn parse_uri_list(list: &str) -> Vec<String> {
    list.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| {
            let rest = l.strip_prefix("file://").or_else(|| l.strip_prefix("FILE://"))?;
            // file://localhost/path and file:///path
            let path = match rest.find('/') {
                Some(0) => rest,
                Some(i) if rest[..i].eq_ignore_ascii_case("localhost") => &rest[i..],
                _ => return None,
            };
            Some(percent_decode(path))
        })
        .collect()
}

/// `file:///a%20b` -> `/a b`. Invalid escapes stay as they are.
pub fn percent_decode(s: &str) -> String {
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            let h = |c: u8| (c as char).to_digit(16);
            if let (Some(a), Some(c)) = (h(b[i + 1]), h(b[i + 2])) {
                out.push((a * 16 + c) as u8);
                i += 3;
                continue;
            }
        }
        out.push(b[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// `/a b` -> `file:///a%20b`.
pub fn path_to_uri(path: &str) -> String {
    let mut out = String::from("file://");
    for b in path.bytes() {
        let c = b as char;
        if c.is_ascii_alphanumeric() || "-._~/".contains(c) {
            out.push(c);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

/// How an entry is told apart when it comes back from the clipboard after Menew wrote it:
/// `t:text`, `f:paths` or `i:file name`.
pub fn own_key(kind: crate::clipboard_db::ClipKind, value: &str) -> String {
    use crate::clipboard_db::ClipKind;
    match kind {
        ClipKind::Text => format!("t:{}", value.trim()),
        ClipKind::File => format!("f:{value}"),
        ClipKind::Image => format!("i:{value}"),
    }
}

/// The type an image file is offered as, from its extension.
pub fn image_mime_of(file_name: &str) -> &'static str {
    match file_name.rsplit('.').next().unwrap_or("").to_ascii_lowercase().as_str() {
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "gif" => "image/gif",
        "bmp" => "image/bmp",
        "tiff" => "image/tiff",
        _ => "image/png",
    }
}

/// The extension an image of this type is kept with.
pub fn image_extension(mime: &str) -> &'static str {
    match mime.to_ascii_lowercase().as_str() {
        "image/jpeg" | "image/jpg" => "jpg",
        "image/webp" => "webp",
        "image/gif" => "gif",
        "image/bmp" | "image/x-bmp" => "bmp",
        "image/tiff" => "tiff",
        _ => "png",
    }
}

/// The name of an image inside the images folder: the first 10 bytes of the SHA-256 of the data in
/// hex plus the extension (`ClipboardManager.poll`), so a second copy of the same image is the same file.
pub fn image_file_name(data: &[u8], mime: &str) -> String {
    format!("{}.{}", crate::sha256::sha256_hex_prefix(data, 10), image_extension(mime))
}

/// Width and height of a PNG, JPEG, GIF, BMP or WebP, read from its header.
pub fn image_size(d: &[u8]) -> Option<(u32, u32)> {
    let be32 = |i: usize| d.get(i..i + 4).map(|b| u32::from_be_bytes([b[0], b[1], b[2], b[3]]));
    let le16 = |i: usize| d.get(i..i + 2).map(|b| u16::from_le_bytes([b[0], b[1]]) as u32);
    let le24 = |i: usize| d.get(i..i + 3).map(|b| u32::from_le_bytes([b[0], b[1], b[2], 0]));
    if d.starts_with(&[0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a]) {
        return Some((be32(16)?, be32(20)?));
    }
    if d.starts_with(b"GIF8") {
        return Some((le16(6)?, le16(8)?));
    }
    if d.starts_with(b"BM") {
        let w = d.get(18..22).map(|b| i32::from_le_bytes([b[0], b[1], b[2], b[3]]))?;
        let h = d.get(22..26).map(|b| i32::from_le_bytes([b[0], b[1], b[2], b[3]]))?;
        return Some((w.unsigned_abs(), h.unsigned_abs()));
    }
    if d.starts_with(&[0xff, 0xd8]) {
        let mut i = 2;
        while i + 9 < d.len() {
            if d[i] != 0xff {
                i += 1;
                continue;
            }
            let marker = d[i + 1];
            if marker == 0xff {
                i += 1;
                continue;
            }
            if (0xc0..=0xcf).contains(&marker) && !matches!(marker, 0xc4 | 0xc8 | 0xcc) {
                let h = u16::from_be_bytes([d[i + 5], d[i + 6]]) as u32;
                let w = u16::from_be_bytes([d[i + 7], d[i + 8]]) as u32;
                return Some((w, h));
            }
            if marker == 0xd8 || marker == 0x01 || (0xd0..=0xd7).contains(&marker) {
                i += 2;
                continue;
            }
            let len = u16::from_be_bytes([d[i + 2], d[i + 3]]) as usize;
            i += 2 + len;
        }
        return None;
    }
    if d.len() > 30 && &d[0..4] == b"RIFF" && &d[8..12] == b"WEBP" {
        match &d[12..16] {
            b"VP8X" => return Some((le24(24)? + 1, le24(27)? + 1)),
            b"VP8L" => {
                let b = d.get(21..25)?;
                let v = u32::from_le_bytes([b[0], b[1], b[2], b[3]]);
                return Some(((v & 0x3fff) + 1, ((v >> 14) & 0x3fff) + 1));
            }
            b"VP8 " => return Some((le16(26)? & 0x3fff, le16(28)? & 0x3fff)),
            _ => return None,
        }
    }
    None
}

