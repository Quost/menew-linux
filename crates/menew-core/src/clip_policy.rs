/// "Paused until I resume" or "paused until this time" (`ClipboardManager.isPaused`).
#[derive(Debug, Clone, Copy, PartialEq, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct PauseState {
    pub paused: bool,
    /// Seconds since 1970 when a timed pause ends; 0 when there is none.
    pub paused_until: f64,
}

impl PauseState {
    pub fn is_paused(&self, now: f64) -> bool {
        self.paused || self.paused_until > now
    }

    /// `pause(minutes:)`: for that many minutes, or until resumed when `None`.
    pub fn pause(&mut self, minutes: Option<u32>, now: f64) {
        match minutes {
            Some(m) => {
                self.paused = false;
                self.paused_until = now + m as f64 * 60.0;
            }
            None => {
                self.paused = true;
                self.paused_until = 0.0;
            }
        }
    }

    pub fn resume(&mut self) {
        self.paused = false;
        self.paused_until = 0.0;
    }

    pub fn path() -> PathBuf {
        crate::clipboard_db::data_dir().join("state.json")
    }

    pub fn load_from(path: &Path) -> Self {
        std::fs::read_to_string(path).ok().and_then(|s| serde_json::from_str(&s).ok()).unwrap_or_default()
    }

    pub fn load() -> Self {
        Self::load_from(&Self::path())
    }

    pub fn save_to(&self, path: &Path) -> std::io::Result<()> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, serde_json::to_string(self).map_err(std::io::Error::other)?)
    }

    pub fn save(&self) -> std::io::Result<()> {
        self.save_to(&Self::path())
    }
}

/// Is `app` one of the ignored apps? Names are compared without case and without `.desktop`.
pub fn is_ignored_app(app: &str, ignored: &[String]) -> bool {
    let norm = |s: &str| s.trim().to_lowercase().trim_end_matches(".desktop").to_string();
    let a = norm(app);
    !a.is_empty() && ignored.iter().any(|i| norm(i) == a)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Capture {
    Yes,
    Paused,
    Ignored,
}

/// Whether a copy may be read at all, before looking at what it holds.
pub fn should_capture(pause: &PauseState, now: f64, ignored: &[String], app: Option<&str>) -> Capture {
    if pause.is_paused(now) {
        Capture::Paused
    } else if app.map(|a| is_ignored_app(a, ignored)).unwrap_or(false) {
        Capture::Ignored
    } else {
        Capture::Yes
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn v(a: &[&str]) -> Vec<String> {
        a.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn plan_order_is_files_text_image() {
        let p = plan(&v(&["image/png", "text/plain", "text/uri-list"])).unwrap();
        assert_eq!(p, vec![Candidate::Files("text/uri-list".into()), Candidate::Text("text/plain".into()), Candidate::Image("image/png".into())]);
        assert_eq!(plan(&v(&["text/html"])).unwrap(), vec![]);
        assert_eq!(plan(&v(&["text/plain", "text/plain;charset=utf-8"])).unwrap(), vec![Candidate::Text("text/plain;charset=utf-8".into())]);
    }

    #[test]
    fn a_password_hint_skips_every_kind() {
        assert_eq!(plan(&v(&["image/png", "x-kde-passwordManagerHint"])), Err(Skip::Secret));
        assert_eq!(plan(&v(&["text/uri-list", "org.nspasteboard.ConcealedType"])), Err(Skip::Secret));
        assert_eq!(plan(&v(&["text/plain", "org.nspasteboard.TransientType"])), Err(Skip::Secret));
    }

    #[test]
    fn uri_lists() {
        let l = "# comment\r\nfile:///home/u/a%20b.txt\r\nhttps://example.com/x\r\nfile://localhost/tmp/c.png\r\nfile://otherhost/x\r\n";
        assert_eq!(parse_uri_list(l), vec!["/home/u/a b.txt".to_string(), "/tmp/c.png".to_string()]);
        assert_eq!(path_to_uri("/home/u/a b.txt"), "file:///home/u/a%20b.txt");
        assert_eq!(percent_decode("100%"), "100%");
        assert_eq!(percent_decode("%zz%41"), "%zzA");
    }

    #[test]
    fn image_names_and_sizes() {
        assert_eq!(image_file_name(b"abc", "image/png"), "ba7816bf8f01cfea4141.png");
        assert_eq!(image_file_name(b"abc", "image/jpeg"), "ba7816bf8f01cfea4141.jpg");
        let mut png = vec![0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13, b'I', b'H', b'D', b'R'];
        png.extend_from_slice(&640u32.to_be_bytes());
        png.extend_from_slice(&480u32.to_be_bytes());
        assert_eq!(image_size(&png), Some((640, 480)));
        let mut gif = b"GIF89a".to_vec();
        gif.extend_from_slice(&[0x20, 0x01, 0x10, 0x00]);
        assert_eq!(image_size(&gif), Some((288, 16)));
        assert_eq!(image_size(b"not an image"), None);
    }

    #[test]
    fn pause_flow() {
        let mut p = PauseState::default();
        assert!(!p.is_paused(1000.0));
        p.pause(Some(15), 1000.0);
        assert!(p.is_paused(1000.0 + 899.0));
        assert!(!p.is_paused(1000.0 + 901.0));
        p.pause(None, 1000.0);
        assert!(p.is_paused(1e12));
        p.resume();
        assert!(!p.is_paused(1000.0));
        // a timed pause replaces "until resumed"
        p.pause(None, 0.0);
        p.pause(Some(60), 5000.0);
        assert!(!p.paused && p.paused_until == 8600.0);
    }

    #[test]
    fn pause_state_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("state.json");
        assert_eq!(PauseState::load_from(&path), PauseState::default());
        let mut p = PauseState::default();
        p.pause(Some(60), 100.0);
        p.save_to(&path).unwrap();
        assert_eq!(PauseState::load_from(&path), p);
    }

    #[test]
    fn capture_decision() {
        let ignored = v(&["org.keepassxc.KeePassXC", "Bitwarden.desktop"]);
        let mut p = PauseState::default();
        assert_eq!(should_capture(&p, 0.0, &ignored, Some("firefox")), Capture::Yes);
        assert_eq!(should_capture(&p, 0.0, &ignored, Some("ORG.keepassxc.keepassxc")), Capture::Ignored);
        assert_eq!(should_capture(&p, 0.0, &ignored, Some("bitwarden")), Capture::Ignored);
        assert_eq!(should_capture(&p, 0.0, &ignored, None), Capture::Yes);
        p.pause(None, 0.0);
        assert_eq!(should_capture(&p, 0.0, &ignored, Some("firefox")), Capture::Paused);
    }
}
